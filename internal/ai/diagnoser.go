// followUpInstruction keeps Findings stable across ordinary questions.
// Saved runs show agents restating the root cause on most answers; without an
// explicit signal every "what is a PDB?" would rewrite the assessment.
const followUpInstruction = "This is a follow-up question. Give the verdict block first and your answer after it. Set revises_assessment=true, with a full verdict block and a new story, only when what you found changed the cause, the certainty, what is unresolved, the recommended step or the recovery status; you may then cite and place results from earlier turns of this investigation. Otherwise set it false, leave summary, root_cause, steps, evidence, ruled_out and unresolved empty, answer in prose without placement markers, and do not restate the earlier assessment. "

const verifyInstruction = "VERIFICATION. Re-check the results behind the earlier verdict's claims and the state the fix changed, then answer as a fresh assessment: say plainly what changed since the earlier assessment and what did not. "

func taskOpening(target string, health *ResourceHealthSignal) string {
	frame := healthFrame(target, health)
	if healthIndicatesProblem(health) {
		return frame + " Find the specific root cause and propose concrete remediation."
	}
	return frame + " Verify quickly with targeted read-only checks. If the resource is genuinely fine, say so briefly and stop; do not manufacture a problem. Dig deeper only when you find concrete evidence of an issue."
}

func healthFrame(target string, health *ResourceHealthSignal) string {
	if health == nil {
		return fmt.Sprintf("Assess %s. Radar did not attach a health summary to this run.", target)
	}
	var b strings.Builder
	switch {
	case health.IssueCount > 0:
		fmt.Fprintf(&b, "Radar currently flags %d active issue%s on %s", health.IssueCount, pluralS(health.IssueCount), target)
		if health.HighestSeverity != "" || health.TopReason != "" {
			b.WriteString(";")
			if health.HighestSeverity != "" {
				fmt.Fprintf(&b, " highest severity %s", health.HighestSeverity)
			}
			if health.TopReason != "" {
				fmt.Fprintf(&b, ": %s", health.TopReason)
			}
		}
		b.WriteString(".")
		for _, line := range health.Issues {
			fmt.Fprintf(&b, " [%s] %s", line.Severity, line.Reason)
			if line.Message != "" {
				fmt.Fprintf(&b, ": %s", line.Message)
			}
			b.WriteString(".")
		}
	case health.Health == "healthy":
		fmt.Fprintf(&b, "Radar currently reports %s as healthy and flags 0 active issues.", target)
	case health.Health != "":
		fmt.Fprintf(&b, "Radar's resource summary currently marks %s as %s, with 0 active issue rows.", target, health.Health)
	default:
		fmt.Fprintf(&b, "Radar currently flags 0 active issues on %s.", target)
	}
	if health.AuditCount > 0 {
		fmt.Fprintf(&b, " Radar audit also reports %d static posture finding%s", health.AuditCount, pluralS(health.AuditCount))
		if health.AuditSeverity != "" || health.TopFinding != "" {
			b.WriteString(";")
			if health.AuditSeverity != "" {
				fmt.Fprintf(&b, " highest severity %s", health.AuditSeverity)
			}
			if health.TopFinding != "" {
				fmt.Fprintf(&b, ": %s", health.TopFinding)
			}
		}
		b.WriteString(".")
		for _, line := range health.AuditFindings {
			fmt.Fprintf(&b, " [%s] %s", line.Severity, line.Reason)
			if line.Message != "" {
				fmt.Fprintf(&b, ": %s", line.Message)
			}
			b.WriteString(".")
		}
		b.WriteString(" Treat audit findings as static posture and remediation priority, not evidence of an active outage.")
	}
	if len(health.AuditMissingInputs) > 0 {
		fmt.Fprintf(&b, " The audit scan could not read these inputs: %s. Zero audit findings do not establish that all checks passed.", strings.Join(health.AuditMissingInputs, ", "))
	}
	return b.String()
}

func healthIndicatesProblem(health *ResourceHealthSignal) bool {
	if health == nil {
		return false
	}
	if health.IssueCount > 0 {
		return true
	}
	switch health.Health {
	case "degraded", "unhealthy", "alert":
		return true
	}
	return false
}

func pluralS(n int) string {
	if n == 1 {
		return ""
	}
	return "s"
}

// MCP config / env / process helpers ----------------------------------------

func mcpConfigDir() string { return filepath.Join(os.TempDir(), "radar-ai-mcp") }

func sweepStaleMCPConfigs() {
	entries, err := os.ReadDir(mcpConfigDir())
	if err != nil {
		return
	}
	for _, e := range entries {
		_ = os.Remove(filepath.Join(mcpConfigDir(), e.Name()))
	}
}

// writeMCPConfig points the CLI at Radar's own local MCP. No auth header — the
// endpoint is loopback-only in standalone mode.
func writeMCPConfig(mcpURL string) (string, func(), error) {
	cfg := map[string]any{"mcpServers": map[string]any{"radar": map[string]any{
		"type": "http", "url": mcpURL,
	}}}
	b, err := json.Marshal(cfg)
	if err != nil {
		return "", func() {}, err
	}
	dir := mcpConfigDir()
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", func() {}, err
	}
	_ = os.Chmod(dir, 0o700)
	f, err := os.CreateTemp(dir, "mcp-*.json")
	if err != nil {
		return "", func() {}, err
	}
	if _, err := f.Write(b); err != nil {
		f.Close()
		os.Remove(f.Name())
		return "", func() {}, err
	}
	f.Close()
	return f.Name(), func() { os.Remove(f.Name()) }, nil
}

var (
	envAllowExact = map[string]bool{
		"PATH": true, "HOME": true, "USER": true, "LOGNAME": true,
		"LANG": true, "LC_ALL": true, "LC_CTYPE": true, "TZ": true,
		"TMPDIR": true, "SHELL": true, "SSL_CERT_FILE": true, "SSL_CERT_DIR": true,
		// AWS creds are passed through so BYO-Bedrock works; the user opted in.
		"AWS_PROFILE": true, "AWS_REGION": true, "AWS_DEFAULT_REGION": true,
	}
	envAllowPrefix = []string{"ANTHROPIC_", "CLAUDE_", "AWS_", "GOOGLE_", "CLOUD_ML_", "VERTEX_"}
)

// scrubbedEnv returns a minimal environment: the CLI ingests untrusted cluster
// data, so it shouldn't inherit unrelated host env. Provider-auth vars pass
// through so subscription / API-key / Bedrock / Vertex all work.
func scrubbedEnv() []string {
	var out []string
	for _, kv := range os.Environ() {
		k, _, ok := strings.Cut(kv, "=")
		if !ok {
			continue
		}
		if envAllowExact[k] {
			out = append(out, kv)
			continue
		}
		for _, p := range envAllowPrefix {
			if strings.HasPrefix(k, p) {
				out = append(out, kv)
				break
			}
		}
	}
	return out
}

type cappedBuffer struct {
	mu    sync.Mutex
	buf   strings.Builder
	limit int
}

func (c *cappedBuffer) Write(p []byte) (int, error) {
	c.mu.Lock()
	defer c.mu.Unlock()
	if rem := c.limit - c.buf.Len(); rem > 0 {
		if len(p) > rem {
			c.buf.Write(p[:rem])
		} else {
			c.buf.Write(p)
		}
	}
	return len(p), nil
}

func (c *cappedBuffer) String() string {
	c.mu.Lock()
	defer c.mu.Unlock()
	return c.buf.String()
}

func formatExitDetails(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return ""
	}
	if r := []rune(s); len(r) > 500 {
		s = string(r[:500]) + "…"
	}
	return ": " + s
}

// agentExitError classifies known failures and preserves both output channels for
// unknown ones, since CLIs disagree about where terminal errors are written.
func agentExitError(name, signinCmd, cliErrText, stderr string) error {
	details := strings.TrimSpace(cliErrText)
	cleanStderr := strings.TrimSpace(stderr)
	if cleanStderr != "" && cleanStderr != details {
		if details != "" {
			details += "\n"
		}
		details += cleanStderr
	}
	low := strings.ToLower(details)
	contains := func(subs ...string) bool {
		for _, s := range subs {
			if strings.Contains(low, s) {
				return true
			}
		}
		return false
	}
	switch {
	case contains("not logged in", "logged out", "not authenticated", "authentication required",
		"sign in required", "login required", "please log in", "/login"):
		return fmt.Errorf("%s isn't signed in. Run `%s` in a terminal to sign in, then try again%s", name, signinCmd, formatExitDetails(details))
	case contains("invalid api key", "no api key"):
		return fmt.Errorf("%s couldn't authenticate. Run `%s` to sign in, or check its API credentials, then try again%s", name, signinCmd, formatExitDetails(details))
	case contains("rate limit", "rate-limit", "429", "529", "quota", "overloaded", "too many requests"):
		return fmt.Errorf("%s is rate-limited or over quota. Wait a moment, then try again%s", name, formatExitDetails(details))
	case contains("max turns", "maximum turns", "turn limit", "error_max_turns"):
		return fmt.Errorf("%s hit its step limit before finishing. Try again, or ask a narrower follow-up%s", name, formatExitDetails(details))
	default:
		return fmt.Errorf("%s stopped unexpectedly%s", name, formatExitDetails(details))
	}
}

// stream-json parsing -------------------------------------------------------

type cliEvent struct {
	Type    string `json:"type"`
	Message *struct {
		Content []struct {
			Type      string          `json:"type"`
			Text      string          `json:"text"`
			Thinking  string          `json:"thinking"`
			ID        string          `json:"id"`
			Name      string          `json:"name"`
			Input     json.RawMessage `json:"input"`
			ToolUseID string          `json:"tool_use_id"`
			Content   json.RawMessage `json:"content"`
			IsError   bool            `json:"is_error"`
		} `json:"content"`
	} `json:"message"`
	Result       string   `json:"result"`
	Subtype      string   `json:"subtype"`
	IsError      bool     `json:"is_error"`
	TotalCostUSD *float64 `json:"total_cost_usd"`
	NumTurns     int      `json:"num_turns"`
	SessionID    string   `json:"session_id"`
	// system/init only.
	Model      string            `json:"model"`
	Tools      []string          `json:"tools"`
	MCPServers []MCPServerStatus `json:"mcp_servers"`
}

// agentReadyEvent reports the CLI's init message as a startup phase. Radar
// tools are counted by their MCP prefix so the count reflects what the model can
// actually call, not what Radar offered.
func agentReadyEvent(model string, tools []string, servers []MCPServerStatus) StreamEvent {
	count := 0
	for _, tool := range tools {
		if strings.HasPrefix(tool, "mcp__radar__") {
			count++
		}
	}
	return StreamEvent{
		Type: "phase", Phase: "ready",
		Model: model, ToolCount: &count, MCPServers: servers,
	}
}

func parseStream(r io.Reader, onEvent func(StreamEvent)) Diagnosis {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 8<<20)
	starts := map[string]time.Time{}
	var finalText string
	var resultIsError bool
	var resultSubtype string
	var cost *float64
	var turns int
	var sessionID string

	// Claude streams its narration as standalone `text` messages interleaved with
	// tool calls. We surface ONLY the narration that directly precedes a tool call —
	// the "let me check the logs" lead-in to an action. We deliberately drop any text
	// that precedes another text, a thinking block, or the `result`: that trailing
	// prose is the model restating its conclusion (root cause / remediation) right
	// before the JSON report, and it would duplicate the structured result card. So
	// we hold the latest text and only flush it at a tool_use boundary.
	var pendingText string
	flushNarration := func() {
		if t := strings.TrimSpace(pendingText); t != "" {
			onEvent(StreamEvent{Type: "thinking", Token: t})
		}
		pendingText = ""
	}

	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" || line[0] != '{' {
			continue
		}
		var ev cliEvent
		if json.Unmarshal([]byte(line), &ev) != nil {
			continue
		}
		switch ev.Type {
		case "system":
			if ev.Subtype == "init" {
				onEvent(agentReadyEvent(ev.Model, ev.Tools, ev.MCPServers))
			}
		case "assistant":
			if ev.Message == nil {
				continue
			}
			for _, b := range ev.Message.Content {
				switch b.Type {
				case "text":
					// Supersede any prior un-flushed narration: the prior text did NOT
					// precede a tool, so it's conclusion prose, not an action lead-in —
					// drop it and keep only the latest.
					pendingText = b.Text
				case "thinking":
					// Narration before a thinking block isn't an action lead-in.
					pendingText = ""
					if b.Thinking != "" {
						onEvent(StreamEvent{Type: "thinking", Token: b.Thinking})
					}
				case "tool_use":
					flushNarration() // interim narration precedes its tool call
					tool := strings.TrimPrefix(b.Name, "mcp__radar__")
					starts[b.ID] = time.Now()
					args, _ := capPayload(strings.TrimSpace(string(b.Input)))
					onEvent(StreamEvent{Type: "step", Step: &StepInfo{
						ID: b.ID, Tool: tool, Status: "running", Summary: args,
					}})
				}
			}
		case "user":
			if ev.Message == nil {
				continue
			}
			for _, b := range ev.Message.Content {
				if b.Type != "tool_result" {
					continue
				}
				var ms *int64
				if t0, ok := starts[b.ToolUseID]; ok {
					v := time.Since(t0).Milliseconds()
					ms = &v
				}
				resultText, evidenceRef := splitInvestigationEvidenceMarker(
					claudeResultText(b.Content),
				)
				res, trunc := capPayload(resultText)
				isError := b.IsError
				onEvent(StreamEvent{Type: "step", Step: &StepInfo{
					ID: b.ToolUseID, Status: "done", Ms: ms, Result: res,
					EvidenceRef: evidenceRef, IsError: &isError, Truncated: trunc,
					producerResult: &resultText,
				}})
			}
		case "result":
			finalText = ev.Result
			resultIsError = ev.IsError
			resultSubtype = ev.Subtype
			cost = ev.TotalCostUSD
			turns = ev.NumTurns
			sessionID = ev.SessionID
		}
	}

	d := diagnosisFromText(finalText)
	d.CostUSD = cost
	d.Turns = turns
	d.SessionID = sessionID
	// A CLI that aborts (auth failure, rate limit, …) reports the reason via an
	// is_error result on stdout, not stderr. Keep that text so the exit-error
	// builder can turn it into an actionable message.
	if resultIsError {
		d.cliErrored = true
		d.cliErrText = strings.TrimSpace(finalText)
		if d.cliErrText == "" {
			d.cliErrText = strings.TrimSpace(resultSubtype)
		}
	}
	return d
}

// maxToolPayload caps a tool's input/result text held in the event log. The MCP
// diagnose producer can legitimately return a 32 KiB aggregate log bundle plus
// a guarded resource, context, events, and change metadata in one JSON envelope.
// Keep enough headroom for that bounded response while still preventing an
// unbounded tool result from entering retained history.
const maxToolPayload = 96 << 10

const (
	investigationEvidenceMarkerPrefix = "[[radar:evidence-ref="
	investigationEvidenceMarkerSuffix = "]]\n"
)

type investigationEvidenceValidator struct {
	registry *investigationrefs.Registry
	scope    string
	claimed  map[string]struct{}
}

// validate promotes an adapter-extracted marker to server-authored provenance
// only when it maps to the exact private-transport payload in the currently
// active turn. The first matching event owns a ref; a later foreign MCP call
// cannot replay a marker and payload it observed earlier in the conversation.
func (v *investigationEvidenceValidator) validate(event StreamEvent) StreamEvent {
	step := event.Step
	if step == nil {
		return event
	}
	producerResult := step.producerResult
	step.producerResult = nil
	// Never accept a provenance bit from an agent adapter or test fixture.
	step.RadarEvidence = false
	if event.Type != "step" || v.scope == "" || step.Status != "done" ||
		step.EvidenceRef == "" || producerResult == nil {
		return event
	}
	retainedResult, truncated := capPayload(*producerResult)
	if retainedResult != step.Result || truncated != step.Truncated {
		return event
	}
	if _, claimed := v.claimed[step.EvidenceRef]; claimed {
		return event
	}
	if !v.registry.Matches(v.scope, step.EvidenceRef, *producerResult) {
		return event
	}
	step.RadarEvidence = true
	v.claimed[step.EvidenceRef] = struct{}{}
	return event
}

// splitInvestigationEvidenceMarker removes the private MCP correlation marker
// before a producer result is capped or persisted. The generated reference gets
// its own typed StepInfo field; malformed or payload-authored lookalikes fail
// closed and remain ordinary result text.
func splitInvestigationEvidenceMarker(result string) (clean, ref string) {
	if !strings.HasPrefix(result, investigationEvidenceMarkerPrefix) {
		return result, ""
	}
	remainder := result[len(investigationEvidenceMarkerPrefix):]
	end := strings.Index(remainder, investigationEvidenceMarkerSuffix)
	if end < 0 {
		return result, ""
	}
	candidate := remainder[:end]
	if !evidenceRefRe.MatchString(candidate) {
		return result, ""
	}
	return remainder[end+len(investigationEvidenceMarkerSuffix):], candidate
}

// capPayload truncates s to maxToolPayload runes, reporting whether it cut.
func capPayload(s string) (string, bool) {
	if r := []rune(s); len(r) > maxToolPayload {
		return string(r[:maxToolPayload]) + "\n…", true
	}
	return s, false
}

// claudeResultText extracts human-readable text from a Claude tool_result's
// content, which can be a plain JSON string ("crashloop"), an MCP content array
// ([{type:"text",text:…}]), or some other JSON value (returned as-is).
func claudeResultText(raw json.RawMessage) string {
	s := strings.TrimSpace(string(raw))
	if s == "" {
		return ""
	}
	switch s[0] {
	case '"':
		var str string
		if json.Unmarshal(raw, &str) == nil {
			return str
		}
	case '[':
		var parts []struct {
			Text string `json:"text"`
		}
		if json.Unmarshal(raw, &parts) == nil {
			var b strings.Builder
			for _, p := range parts {
				b.WriteString(p.Text)
			}
			if b.Len() > 0 {
				return b.String()
			}
		}
	}
	return s
}
