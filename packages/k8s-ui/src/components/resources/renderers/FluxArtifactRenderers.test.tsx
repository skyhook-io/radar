import { describe, expect, it } from 'vitest'
import { renderToString } from 'react-dom/server'
import { ArtifactGeneratorRenderer, ExternalArtifactRenderer } from './FluxArtifactRenderers'
import { ExternalArtifactCell } from './flux-cells'

const text = (html: string) => html.replace(/<!-- -->/g, '')
const navigate = () => {}

describe('ExternalArtifactRenderer', () => {
  it('names its generator and shortens the revision', () => {
    const html = text(renderToString(<ExternalArtifactRenderer onNavigate={navigate} data={{
      apiVersion: 'source.toolkit.fluxcd.io/v1', kind: 'ExternalArtifact', metadata: { name: 'app', namespace: 'flux-system' },
      spec: { sourceRef: { apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', name: 'gen' } },
      status: { artifact: { revision: 'latest@sha256:53884aebf2e5aa11223344', size: 2048, lastUpdateTime: '2026-11-10T09:00:00Z' }, conditions: [{ type: 'Ready', status: 'True' }] },
    }} />))
    expect(html).toContain('Generated by')
    expect(html).toContain('>gen<')
    expect(html).toContain('latest@53884aebf2e5')
    expect(html).toContain('2 KB')
    expect(html).not.toContain('No artifact recorded')
  })

  it('says when status records no artifact yet', () => {
    const html = text(renderToString(<ExternalArtifactRenderer data={{
      apiVersion: 'source.toolkit.fluxcd.io/v1', kind: 'ExternalArtifact', metadata: { name: 'app', namespace: 'flux-system' },
      spec: {}, status: {},
    }} />))
    expect(html).toContain('No artifact recorded in status yet')
  })
})

describe('ArtifactGeneratorRenderer', () => {
  it('lists sources by alias, caps the artifacts and the copy rules', () => {
    const inventory = Array.from({ length: 60 }, (_, i) => ({ name: `art-${i}`, namespace: 'flux-system' }))
    const artifacts = Array.from({ length: 8 }, (_, i) => ({ name: `art-${i}`, copy: [{ from: `@repo/charts/app-${i}/**`, to: '@artifact/' }] }))
    const html = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={{
      apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', metadata: { name: 'gen', namespace: 'flux-system' },
      spec: { sources: [{ alias: 'repo', kind: 'GitRepository', name: 'platform' }], artifacts },
      status: { inventory, conditions: [{ type: 'Ready', status: 'True' }] },
    }} />))
    expect(html).toContain('repo')
    expect(html).toContain('>platform<')
    expect(html).toContain('60')
    expect(html).toContain('+10 more')
    expect(html).toContain('Copy rules')
    const copyRules = html.match(/<button\b[\s\S]*?<\/button>/g)?.find(button => button.includes('Copy rules'))
    expect(copyRules).toContain('aria-expanded="true"')
  })

  it('links every source kind, leaves namespaces out of the artifacts, and says when there is no inventory', () => {
    const data = {
      apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', metadata: { name: 'gen', namespace: 'flux-system' },
      spec: { sources: [{ alias: 'chart', kind: 'HelmChart', name: 'podinfo' }, { alias: 'base', kind: 'ExternalArtifact', name: 'base' }] },
      status: { inventory: [{ kind: 'Namespace', name: 'team-a' }, { kind: 'ExternalArtifact', name: 'app', namespace: 'team-a' }] },
    }
    const html = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={data} />))
    expect(html).toMatch(/<button[^>]*>[^<]*podinfo/)
    expect(html).toMatch(/<button[^>]*>[^<]*base/)
    expect(html).toContain('Artifacts (1)')
    expect(html).not.toContain('team-a<')
    const none = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={{ ...data, status: {} }} />))
    expect(none).toContain('Radar can&#x27;t read an inventory in this generator&#x27;s status.')
    expect(none).not.toContain('Artifacts (0)')
  })

  it('shows a generator paused by annotation as suspended, not as its stale failure', () => {
    const failing = {
      apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator',
      metadata: { name: 'gen', namespace: 'flux-system' },
      spec: { sources: [{ alias: 'repo', kind: 'GitRepository', name: 'platform' }] },
      status: { inventory: [], conditions: [{ type: 'Ready', status: 'False', reason: 'BuildFailed', message: 'old failure' }] },
    }
    const paused = { ...failing, metadata: { ...failing.metadata, annotations: { 'source.extensions.fluxcd.io/reconcile': 'disabled' } } }
    const count = (html: string) => html.split('old failure').length - 1
    const failingHtml = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={failing} />))
    const pausedHtml = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={paused} />))
    expect(pausedHtml).toContain('Suspended')
    expect(failingHtml).not.toContain('Suspended')
    // The failure banner and status message go; the condition history keeps it.
    expect(count(pausedHtml)).toBe(1)
    expect(count(failingHtml)).toBeGreaterThan(1)
  })
})

describe('ExternalArtifactCell', () => {
  it('names the generator, or another producer by kind and name', () => {
    const cell = (sourceRef: any) => renderToString(<ExternalArtifactCell column="producer" resource={{ apiVersion: 'source.toolkit.fluxcd.io/v1', kind: 'ExternalArtifact', spec: { sourceRef } }} />)
    expect(cell({ apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', name: 'gen' })).toContain('>gen<')
    expect(cell({ apiVersion: 'example.com/v1', kind: 'Builder', name: 'b' })).toContain('>Builder/b<')
    expect(cell(undefined)).toContain('>-<')
  })
})

describe('ExternalArtifactRenderer producer', () => {
  it('names a producer that is not an ArtifactGenerator', () => {
    const html = text(renderToString(<ExternalArtifactRenderer onNavigate={navigate} data={{
      apiVersion: 'source.toolkit.fluxcd.io/v1', kind: 'ExternalArtifact', metadata: { name: 'app', namespace: 'team' },
      spec: { sourceRef: { apiVersion: 'example.com/v1', kind: 'Builder', name: 'b' } },
    }} />))
    expect(html).toContain('Produced by')
    expect(html).toContain('Builder/b')
    expect(html).not.toContain('Generated by')
  })
})
