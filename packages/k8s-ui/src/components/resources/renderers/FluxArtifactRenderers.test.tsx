import { describe, expect, it } from 'vitest'
import { renderToString } from 'react-dom/server'
import { ArtifactGeneratorRenderer, ExternalArtifactRenderer } from './FluxArtifactRenderers'

const text = (html: string) => html.replace(/<!-- -->/g, '')
const navigate = () => {}

describe('ExternalArtifactRenderer', () => {
  it('names its generator and shortens the revision', () => {
    const html = text(renderToString(<ExternalArtifactRenderer onNavigate={navigate} data={{
      apiVersion: 'source.toolkit.fluxcd.io/v1', kind: 'ExternalArtifact', metadata: { name: 'app', namespace: 'flux-system' },
      spec: { sourceRef: { apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', name: 'gen' } },
      status: { artifact: { revision: 'latest@sha256:53884aebf2e5aa11223344', size: 2048, lastUpdateTime: '2026-11-10T09:00:00Z' }, conditions: [{ type: 'Ready', status: 'True' }] },
    }} />))
    expect(html).toContain('Generated by')
    expect(html).toContain('>gen<')
    expect(html).toContain('latest@53884aebf2e5')
    expect(html).toContain('2 KB')
  })
})

describe('ArtifactGeneratorRenderer', () => {
  it('lists sources by alias, caps the artifacts and the copy rules', () => {
    const inventory = Array.from({ length: 60 }, (_, i) => ({ name: `art-${i}`, namespace: 'flux-system' }))
    const artifacts = Array.from({ length: 8 }, (_, i) => ({ name: `art-${i}`, copy: [{ from: `@repo/charts/app-${i}/**`, to: '@artifact/' }] }))
    const html = text(renderToString(<ArtifactGeneratorRenderer onNavigate={navigate} data={{
      apiVersion: 'source.extensions.fluxcd.io/v1beta1', kind: 'ArtifactGenerator', metadata: { name: 'gen', namespace: 'flux-system' },
      spec: { sources: [{ alias: 'repo', kind: 'GitRepository', name: 'platform' }], artifacts },
      status: { inventory, conditions: [{ type: 'Ready', status: 'True' }] },
    }} />))
    expect(html).toContain('repo')
    expect(html).toContain('>platform<')
    expect(html).toContain('60')
    expect(html).toContain('+10 more')
    expect(html).toContain('Copy rules')
  })
})
