import { Boxes, FileArchive, GitBranch } from 'lucide-react'
import { Section, PropertyList, Property, ConditionsSection, ProblemAlerts, ResourceLink } from '../../ui/drawer-components'
import { formatBytes } from '../../../utils/format'
import { GitOpsStatusBadge } from '../../gitops'
import { fluxConditionsToGitOpsStatus, type FluxCondition } from '../../../types/gitops'
import { TimeValue } from '../../ui/ScheduleValue'
import { Tooltip } from '../../ui/Tooltip'
import { getExternalArtifactGenerator, shortArtifactRevision } from '../resource-utils-flux'

type NavigateRef = { kind: string; namespace: string; name: string; group?: string }

interface Props {
  data: any
  onNavigate?: (ref: NavigateRef) => void
}

const SOURCE_PLURALS: Record<string, string> = {
  GitRepository: 'gitrepositories',
  OCIRepository: 'ocirepositories',
  Bucket: 'buckets',
}
const MAX_ARTIFACTS = 50
const MAX_COPY_RULES = 5

function FluxStatus({ data }: { data: any }) {
  const conditions = (data.status?.conditions || []) as FluxCondition[]
  const status = fluxConditionsToGitOpsStatus(conditions, data.spec?.suspend === true, {
    generation: data.metadata?.generation,
    observedGeneration: data.status?.observedGeneration,
  })
  const problems: Array<{ color: 'red' | 'yellow'; message: string }> = []
  if (status.health === 'Degraded' && status.message) problems.push({ color: 'red', message: status.message })
  return (
    <>
      <ProblemAlerts problems={problems} />
      <Section title="Status">
        <GitOpsStatusBadge status={status} showHealth={false} />
      </Section>
    </>
  )
}

export function ExternalArtifactRenderer({ data, onNavigate }: Props) {
  const artifact = data.status?.artifact || {}
  const sourceRef = data.spec?.sourceRef || {}
  const generator = getExternalArtifactGenerator(data)
  const namespace = data.metadata?.namespace || ''
  return (
    <>
      <FluxStatus data={data} />
      <Section title="Artifact" icon={FileArchive}>
        <PropertyList>
          {artifact.revision && (
            <Property label="Revision" value={<Tooltip content={artifact.revision}><span className="font-mono">{shortArtifactRevision(artifact.revision)}</span></Tooltip>} />
          )}
          {typeof artifact.size === 'number' && <Property label="Size" value={formatBytes(artifact.size)} />}
          {artifact.lastUpdateTime && <Property label="Last update" value={<TimeValue timestamp={artifact.lastUpdateTime} />} />}
        </PropertyList>
      </Section>
      {generator && (
        <Section title="Generated by" icon={Boxes}>
          <ResourceLink name={generator} kind="artifactgenerators" group="source.extensions.fluxcd.io" namespace={sourceRef.namespace || namespace} onNavigate={onNavigate} />
        </Section>
      )}
      <ConditionsSection conditions={data.status?.conditions} />
    </>
  )
}

export function ArtifactGeneratorRenderer({ data, onNavigate }: Props) {
  const namespace = data.metadata?.namespace || ''
  const sources: any[] = (data.spec?.sources || []).filter((s: any) => s?.kind && s?.name)
  const inventory: any[] = data.status?.inventory || []
  const artifacts: any[] = data.spec?.artifacts || []
  return (
    <>
      <FluxStatus data={data} />
      {sources.length > 0 && (
        <Section title={`Sources (${sources.length})`} icon={GitBranch}>
          <div className="space-y-1 text-sm">
            {sources.map((s, i) => (
              <div key={i} className="flex items-baseline gap-2">
                {s.alias && <span className="font-mono text-theme-text-tertiary">@{s.alias}</span>}
                <span className="text-theme-text-tertiary">{s.kind}</span>
                {SOURCE_PLURALS[s.kind] ? (
                  <ResourceLink name={s.name} kind={SOURCE_PLURALS[s.kind]} group="source.toolkit.fluxcd.io" namespace={s.namespace || namespace} onNavigate={onNavigate} />
                ) : (
                  <span className="text-theme-text-primary">{s.name}</span>
                )}
              </div>
            ))}
          </div>
        </Section>
      )}
      <Section title={`Artifacts (${inventory.length})`} icon={FileArchive}>
        {inventory.length === 0 ? (
          <span className="text-sm text-theme-text-tertiary">No artifacts generated yet.</span>
        ) : (
          <div className="flex flex-wrap gap-x-3 gap-y-1 text-sm">
            {inventory.slice(0, MAX_ARTIFACTS).map((a, i) => (
              <ResourceLink key={i} name={a.name} kind="externalartifacts" group="source.toolkit.fluxcd.io" namespace={a.namespace || namespace} onNavigate={onNavigate} />
            ))}
            {inventory.length > MAX_ARTIFACTS && <span className="text-theme-text-tertiary">+{inventory.length - MAX_ARTIFACTS} more</span>}
          </div>
        )}
      </Section>
      {artifacts.length > 0 && (
        <Section title="Copy rules" defaultExpanded={false}>
          <div className="space-y-2 text-xs">
            {artifacts.slice(0, MAX_COPY_RULES).map((a, i) => (
              <div key={i}>
                <div className="font-medium text-theme-text-primary">{a.name}</div>
                {(a.copy || []).map((c: any, j: number) => (
                  <div key={j} className="font-mono text-theme-text-secondary">{c.from} → {c.to}</div>
                ))}
              </div>
            ))}
            {artifacts.length > MAX_COPY_RULES && <div className="text-theme-text-tertiary">+{artifacts.length - MAX_COPY_RULES} more artifacts</div>}
          </div>
        </Section>
      )}
      <ConditionsSection conditions={data.status?.conditions} />
    </>
  )
}
